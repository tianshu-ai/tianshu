// Core read-only API: `/api/me`, `/api/models`, `/api/tools`,
// `/api/skills`. These power the chat shell's identity badge,
// model picker, and worker-agents allow-list pickers.
//
// All four assume tenant middleware has run (req.ctx is set); each
// scopes to the calling user when appropriate. Side-effect-free \u2014
// no DB writes, no plugin state mutation.

import express, { type Express, type Request, type Response } from "express";
import { DEV_TENANT_ID, DEV_USER_ID, SETUP_TENANT_ID } from "../core/dev-mode.js";
import { listModels, getDefaultModel } from "../core/llm.js";
import type { PluginRegistry } from "../core/plugins/registry.js";
import {
  loadGlobalConfig,
  writeGlobalConfig,
  type ProviderEntry,
  type ModelEntry,
} from "../core/config.js";
import { getTianshuHome } from "../core/paths.js";
import { getPackageVersion } from "../setup/repo-root.js";
import { isSuperAdmin, resolveTenantRole, tenantsForUser } from "../core/auth/identity.js";
import { getUserStore } from "../core/auth/user-store.js";
import { isTenantDisabled } from "../core/config.js";
import { requireAdmin, requireSuperAdmin } from "./routes-auth.js";

// Sentinel the client echoes back for an apiKey field it did NOT
// change. Lets the UI edit other fields (or reorder models) without
// ever seeing or having to re-enter the real secret — we treat the
// sentinel as "keep the stored value".
const API_KEY_MASK = "__stored__";

// ─── Session messages endpoint (read-only) ───────────────────────
// Used by ChatTranscript (UiPrimitives) to render worker session
// transcripts with the same MessageBubble as the main chat.

export interface MountCoreRoutesDeps {
  /** Registry used by /api/tools and /api/skills to enumerate the
   *  current tenant's catalog. Closures resolve it at request time
   *  so plugin enable/disable cycles take effect immediately. */
  pluginRegistry: PluginRegistry;
  /** All existing tenant ids — for the /api/me tenant switcher list. */
  listTenants: () => string[];
  /** Global tenant operations — used by diagnostics endpoints. */
  globalOps?: import("../core/global-ops.js").GlobalOps;
}

import * as fs from "node:fs";
import * as pathMod from "node:path";
import { llmChat, type LlmChatMessage } from "../core/llm-chat.js";
import { listMessagesForSession } from "../chat/messages.js";
import { enqueue } from "../chat/session-inbox.js";
import { toWire } from "../chat/ws-protocol.js";

export function mountCoreRoutes(
  app: Express,
  deps: MountCoreRoutesDeps,
): void {
  const { pluginRegistry } = deps;

  // ─── General-purpose LLM chat endpoint ─────────────────────────
  // POST /api/llm/chat
  // Body: { model?, messages: [{role, content}], system?, maxTokens?, temperature? }
  // Returns: { ok, text, model, usage?, error? }
  //
  // Available to any authenticated request (board apps, plugins, etc.).
  app.post("/api/llm/chat", async (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(401).json({ error: "not authenticated" });
      return;
    }
    const body = req.body as {
      model?: string;
      messages?: LlmChatMessage[];
      system?: string;
      maxTokens?: number;
      temperature?: number;
    };
    if (!body.messages || !Array.isArray(body.messages) || body.messages.length === 0) {
      res.status(400).json({ error: "messages is required (non-empty array)" });
      return;
    }
    const result = await llmChat({
      tenantId: req.ctx.tenant.tenantId,
      model: body.model,
      messages: body.messages,
      system: body.system,
      maxTokens: body.maxTokens,
      temperature: body.temperature,
    });
    res.json(result);
  });

  // Serve images generated by the built-in generate_image host tool.
  // Files live in <workspace>/users/<userId>/generated-images/*.
  // GET /api/generated-images/:filename
  app.get("/api/generated-images/:filename", (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(500).json({ error: "no_ctx" });
      return;
    }
    const filenameRaw = req.params.filename;
    const filename = typeof filenameRaw === "string" ? filenameRaw : "";
    // Only allow simple filenames; block traversal and separators.
    if (
      !filename ||
      filename.includes("..") ||
      filename.includes("/") ||
      filename.includes("\\")
    ) {
      res.status(400).json({ error: "invalid path" });
      return;
    }
    if (!/\.(png|jpe?g|webp|gif)$/i.test(filename)) {
      res.status(400).json({ error: "unsupported type" });
      return;
    }
    const userId =
      typeof req.ctx.userId === "string" ? req.ctx.userId : "";
    if (!userId) {
      res.status(401).json({ error: "no user context" });
      return;
    }
    const userHome = req.ctx.tenant.userHomeDir(userId);
    const absPath = pathMod.join(userHome, "generated-images", filename);
    if (!fs.existsSync(absPath)) {
      res.status(404).json({ error: "not found" });
      return;
    }
    const ext = pathMod.extname(absPath).toLowerCase();
    const mime: Record<string, string> = {
      ".png": "image/png",
      ".jpg": "image/jpeg",
      ".jpeg": "image/jpeg",
      ".webp": "image/webp",
      ".gif": "image/gif",
    };
    res.setHeader("Content-Type", mime[ext] ?? "application/octet-stream");
    res.setHeader("Cache-Control", "private, max-age=3600");
    fs.createReadStream(absPath).pipe(res);
  });

  // GET /api/message-image/:msgId/:idx — serve inline base64 images
  // from persisted user messages (clipboard pastes that have no disk path).
  app.get("/api/message-image/:msgId/:idx", (req: Request, res: Response) => {
    if (!req.ctx) { res.status(401).json({ error: "not authenticated" }); return; }
    const msgId = typeof req.params.msgId === "string" ? req.params.msgId : "";
    const idx = parseInt(typeof req.params.idx === "string" ? req.params.idx : "", 10);
    if (!msgId || isNaN(idx) || idx < 0) { res.status(400).json({ error: "invalid params" }); return; }
    const row = req.ctx.tenant.db
      .prepare<[string], { content: string } | undefined>(
        `SELECT content FROM messages WHERE id = ?`,
      )
      .get(msgId);
    if (!row) { res.status(404).json({ error: "not found" }); return; }
    try {
      const parsed = JSON.parse(row.content);
      const parts = Array.isArray(parsed.content) ? parsed.content : [];
      const imageParts = parts.filter((p: any) => p.type === "image" && typeof p.data === "string" && !p.path);
      const part = imageParts[idx];
      if (!part) { res.status(404).json({ error: "image not found" }); return; }
      const buf = Buffer.from(part.data, "base64");
      const mime = typeof part.mimeType === "string" ? part.mimeType : "image/png";
      res.setHeader("Content-Type", mime);
      res.setHeader("Cache-Control", "private, max-age=86400, immutable");
      res.end(buf);
    } catch {
      res.status(500).json({ error: "parse error" });
    }
  });

  // GET /api/sessions/:id/messages — read-only session transcript
  // Returns WireMessage[] for the given session. Used by the
  // ChatTranscript UiPrimitive to render worker transcripts with
  // the same MessageBubble as the main chat.
  app.get("/api/sessions/:id/messages", (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(401).json({ error: "not authenticated" });
      return;
    }
    const sessionId = req.params.id as string;
    if (!sessionId) {
      res.status(400).json({ error: "session id required" });
      return;
    }
    const messages = listMessagesForSession(req.ctx.tenant, sessionId);
    res.json({ messages: messages.map((m) => toWire(m)) });
  });

  app.get("/api/me", (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(500).json({ error: "no_ctx" });
      return;
    }
    const { tenant, userId } = req.ctx;
    const def = getDefaultModel(tenant.config);
    // Human-friendly identity for the UI. sessionResolver stashes the
    // authed name/email/provider in identityMeta; prefer name → email →
    // raw id so the sidebar shows "admin" not "ul_5457...". Role is
    // resolved against the current tenant (super-admin > db role >
    // member); in dev mode (no meta) it's the dev user.
    const meta = req.ctx.identityMeta ?? {};
    const displayName = meta.name || meta.email || userId;
    const authCfg = loadGlobalConfig().auth ?? {};
    const role = authCfg.enabled
      ? resolveTenantRole(authCfg, getUserStore(), {
          userId,
          tenantId: tenant.tenantId,
          email: meta.email,
          username: meta.provider === "local" ? meta.name : undefined,
        })
      : "admin"; // dev mode: de-facto admin
    // Tenants this user may enter (for the tenant switcher).
    // Auth mode: membership + super-admin, minus disabled.
    // No-auth mode: all tenants — the user should be able to
    // freely switch without any auth gating.
    // Filter out the maintenance tenant — it has its own sidebar
    // entry and should not appear in the tenant-switcher dropdown.
    const tenants = (authCfg.enabled
      ? tenantsForUser(
          authCfg,
          getUserStore(),
          {
            userId,
            email: meta.email,
            username: meta.provider === "local" ? meta.name : undefined,
          },
          deps.listTenants,
          isTenantDisabled,
        )
      : deps.listTenants().filter((id) => !isTenantDisabled(id))
    ).filter((id) => id !== SETUP_TENANT_ID);
    const superAdmin = authCfg.enabled
      ? isSuperAdmin(authCfg, {
          email: meta.email,
          username: meta.provider === "local" ? meta.name : undefined,
        })
      : true; // dev mode
    res.json({
      tenantId: tenant.tenantId,
      userId,
      displayName,
      email: meta.email ?? null,
      provider: meta.provider ?? null,
      role,
      superAdmin,
      tenants,
      config: { branding: tenant.config.branding ?? null },
      defaultModel: def
        ? { id: def.id, name: def.name, provider: def.providerId }
        : null,
      devTenant:
        tenant.tenantId === DEV_TENANT_ID && userId === DEV_USER_ID,
      appVersion: getPackageVersion(),
    });
  });

  app.get("/api/models", (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(500).json({ error: "no_ctx" });
      return;
    }
    const list = listModels(req.ctx.tenant.config).map((m) => ({
      id: m.id,
      name: m.name,
      provider: m.providerId,
      group: m.group ?? null,
      contextWindow: m.contextWindow,
      reasoning: m.reasoning,
    }));
    res.json({
      models: list,
      defaultModel: req.ctx.tenant.config.defaultModel ?? null,
    });
  });

  /**
   * Tool catalog for the current tenant. Used by the worker-agents
   * settings page to render an allow-list picker instead of the
   * old comma-separated freetext field.
   *
   * Returns ALL tools the host registry knows about (host built-ins
   * + every active plugin's contributions). Per-agent allow-list
   * filtering happens at the worker; this endpoint is just the
   * universe to pick from.
   */
  app.get("/api/tools", (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(500).json({ error: "no_ctx" });
      return;
    }
    const entries = pluginRegistry.toolsForTenant(req.ctx.tenant.tenantId);
    // De-dupe by tool name; if two plugins shipped the same name we
    // still only show it once. Stable sort by name for the UI.
    const byName = new Map<
      string,
      { name: string; description: string; pluginId: string }
    >();
    for (const { pluginId, tool } of entries) {
      if (byName.has(tool.schema.name)) continue;
      byName.set(tool.schema.name, {
        name: tool.schema.name,
        description: tool.schema.description ?? "",
        pluginId,
      });
    }
    const tools = [...byName.values()].sort((a, b) =>
      a.name.localeCompare(b.name),
    );
    res.json({ tools });
  });

  /**
   * Skill catalog for the current tenant. Same role as /api/tools \u2014
   * the universe of skills available (host-shipped + plugin-shipped)
   * for the worker-agents allow-list picker.
   */
  app.get("/api/skills", (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(500).json({ error: "no_ctx" });
      return;
    }
    const skills = pluginRegistry.skillsForTenant(
      req.ctx.tenant.tenantId,
    );
    // Same shape as /api/tools \u2014 just the bits the picker UI needs.
    // Description is the SKILL.md frontmatter so the picker can render
    // a tooltip; the body markdown stays server-side.
    const out = skills
      .map((s) => ({
        name: s.name,
        description: s.description,
        pluginId: s.source.pluginId,
        // Surface frontmatter `scope:` so the worker-agents page can
        // hide \"scope: main\" skills from a worker's effective list.
        // Undefined = visible to both.
        scope: s.scope,
      }))
      .sort((a, b) => a.name.localeCompare(b.name));
    res.json({ skills: out });
  });

  // ── Models / provider catalog admin ──────────────────────────────
  //
  // Read + maintain the provider catalog in the GLOBAL config
  // (~/.tianshu/config.json → models.providers), which is what the
  // Settings "Models" page edits. GET masks apiKeys (never leaked to
  // the browser); PUT preserves a stored key when the client sends
  // back the API_KEY_MASK sentinel. Config is re-read from disk on
  // every request (buildTenantContext → resolveTenantConfig), so an
  // external edit to config.json shows up on the next GET with no
  // restart, and a PUT here is visible to the next model resolution.

  app.get("/api/admin/models/providers", requireSuperAdmin, (req: Request, res: Response) => {
    if (!req.ctx) {
      res.status(500).json({ error: "no_ctx" });
      return;
    }
    try {
      const cfg = loadGlobalConfig(getTianshuHome());
      const providers = cfg.models?.providers ?? {};
      res.json({
        providers: maskProviders(providers),
        defaultModelId: cfg.models?.defaultModelId ?? null,
        defaultModel: cfg.defaultModel ?? null,
        imageGenModelId: cfg.models?.imageGenModelId ?? null,
        compactionModelId: cfg.models?.compaction?.model ?? null,
        outputLanguage: cfg.outputLanguage ?? "auto",
      });
    } catch (err) {
      res.status(500).json({
        error: "config_read_failed",
        message: err instanceof Error ? err.message : String(err),
      });
    }
  });

  app.put(
    "/api/admin/models/providers",
    requireSuperAdmin,
    express.json({ limit: "1mb" }),
    (req: Request, res: Response) => {
      if (!req.ctx) {
        res.status(500).json({ error: "no_ctx" });
        return;
      }
      try {
        const cfg = loadGlobalConfig(getTianshuHome());
        const prev = cfg.models?.providers ?? {};
        const parsed = parseProvidersInput(
          (req.body as { providers?: unknown } | undefined)?.providers,
          prev,
        );
        if ("error" in parsed) {
          res.status(400).json(parsed);
          return;
        }
        const body = req.body as {
          defaultModelId?: unknown;
          defaultModel?: unknown;
          imageGenModelId?: unknown;
          compactionModelId?: unknown;
        };
        const nextModels = {
          ...(cfg.models ?? {}),
          providers: parsed.value,
        };
        // Unify onto models.defaultModelId (Yu, 2026-09-17 00:58).
        // Accept either field name in the request body — clients
        // that still POST { defaultModel } get their value written
        // to the new location. If both are set we prefer
        // defaultModelId (the canonical field).
        const incomingDefault =
          typeof body.defaultModelId === "string"
            ? body.defaultModelId
            : typeof body.defaultModel === "string"
              ? body.defaultModel
              : undefined;
        if (incomingDefault !== undefined) {
          nextModels.defaultModelId = incomingDefault || undefined;
        }
        if (typeof body.imageGenModelId === "string") {
          nextModels.imageGenModelId = body.imageGenModelId || undefined;
        } else if (body.imageGenModelId === null) {
          nextModels.imageGenModelId = undefined;
        }
        // Compaction model
        if (typeof body.compactionModelId === "string" || body.compactionModelId === null) {
          const compaction = { ...(nextModels.compaction ?? {}) };
          if (body.compactionModelId) {
            compaction.model = body.compactionModelId;
          } else {
            delete compaction.model;
          }
          // Keep compaction object if it has other fields, remove if empty
          if (Object.keys(compaction).length > 0) {
            nextModels.compaction = compaction;
          } else {
            delete nextModels.compaction;
          }
        }
        const nextCfg = { ...cfg, models: nextModels };
        // Clear the deprecated top-level key on any write so a
        // migration in progress converges. New writes never
        // populate it again.
        if (incomingDefault !== undefined) {
          delete nextCfg.defaultModel;
        }
        const lang = (req.body as { outputLanguage?: unknown }).outputLanguage;
        if (lang === "en" || lang === "zh" || lang === "de" || lang === "ja" || lang === "ko") {
          nextCfg.outputLanguage = lang;
        } else if (lang === "auto" || lang === "" || lang === null) {
          delete nextCfg.outputLanguage;
        }
        writeGlobalConfig(nextCfg, getTianshuHome());
        res.json({
          providers: maskProviders(parsed.value),
          defaultModelId: nextModels.defaultModelId ?? null,
          defaultModel: nextCfg.defaultModel ?? null,
          imageGenModelId: nextModels.imageGenModelId ?? null,
          compactionModelId: nextModels.compaction?.model ?? null,
          outputLanguage: nextCfg.outputLanguage ?? "auto",
        });
      } catch (err) {
        res.status(500).json({
          error: "config_write_failed",
          message: err instanceof Error ? err.message : String(err),
        });
      }
    },
  );

  // ── User preferences (key-value, persisted in tenant DB) ────────

  // ── Change own password (any logged-in user) ─────────────
  app.patch("/api/me/password", (req: Request, res: Response) => {
    if (!req.ctx) { res.status(401).json({ error: "not_authenticated" }); return; }
    const { userId } = req.ctx;
    const body = req.body as { oldPassword?: string; newPassword?: string };
    const oldPw = body.oldPassword ?? "";
    const newPw = body.newPassword ?? "";
    if (newPw.length < 6) {
      res.status(400).json({ error: "weak_password", detail: "password ≥6" });
      return;
    }
    const store = getUserStore();
    const user = store.getById(userId);
    if (!user) { res.status(404).json({ error: "user_not_found" }); return; }
    // Verify old password via authenticate (username + password)
    if (!store.authenticate(user.username, oldPw)) {
      res.status(403).json({ error: "wrong_password" });
      return;
    }
    store.setPassword(userId, newPw);
    res.json({ ok: true });
  });

  app.get("/api/preferences/:key", (req: Request, res: Response) => {
    if (!req.ctx) { res.status(500).json({ error: "no_ctx" }); return; }
    const { userId } = req.ctx;
    const key = String(req.params.key);
    const row = req.ctx.tenant.db
      .prepare<[string, string], { value: string | null }>("SELECT value FROM user_preferences WHERE user_id = ? AND key = ?")
      .get(userId, key);
    res.json({ key, value: row?.value ?? null });
  });

  app.post("/api/preferences/:key", (req: Request, res: Response) => {
    if (!req.ctx) { res.status(500).json({ error: "no_ctx" }); return; }
    const { userId } = req.ctx;
    const key = String(req.params.key);
    const value = (req.body as { value?: unknown })?.value;
    const val = value == null ? null : String(value);
    req.ctx.tenant.db
      .prepare("INSERT OR REPLACE INTO user_preferences (user_id, key, value) VALUES (?, ?, ?)")
      .run(userId, key, val);
    res.json({ ok: true });
  });

  // ── Diagnostics: unanswered sessions ──────────────────────────
  // Find sessions where the last message is user/system role with
  // no assistant reply — "sent but never replied" pattern.
  app.get("/api/admin/diagnostics/unanswered", requireSuperAdmin, (req: Request, res: Response) => {
    if (!deps.globalOps) {
      res.status(500).json({ error: "globalOps not available" });
      return;
    }
    const since = Number(req.query.since) || (Date.now() - 24 * 60 * 60 * 1000);
    const tenantFilter = req.query.tenant as string | undefined;
    const results: Array<{
      tenantId: string;
      sessionId: string;
      sessionKind: string;
      sessionTitle: string | null;
      lastMessageRole: string;
      lastMessageContent: string;
      lastMessageAt: number;
      messageCount: number;
    }> = [];

    const tenants = tenantFilter ? [tenantFilter] : deps.listTenants();
    for (const tenantId of tenants) {
      try {
        const ctx = deps.globalOps!.open(tenantId);
        const rows = ctx.db.prepare<[number], {
          session_id: string;
          kind: string;
          title: string | null;
          last_role: string;
          last_content: string;
          last_at: number;
          msg_count: number;
        }>(`
          SELECT
            s.id AS session_id,
            s.kind,
            s.title,
            m.role AS last_role,
            SUBSTR(m.content, 1, 500) AS last_content,
            m.created_at AS last_at,
            (SELECT COUNT(*) FROM messages WHERE session_id = s.id) AS msg_count
          FROM sessions s
          JOIN messages m ON m.session_id = s.id
            AND m.created_at = (
              SELECT MAX(m2.created_at) FROM messages m2
              WHERE m2.session_id = s.id AND m2.entry_type IN ('message', 'fork_tail')
            )
          WHERE s.status IN ('active', 'compacted')
            AND m.role IN ('user', 'system')
            AND m.created_at > ?
          ORDER BY m.created_at DESC
          LIMIT 100
        `).all(since);

        for (const r of rows) {
          results.push({
            tenantId,
            sessionId: r.session_id,
            sessionKind: r.kind,
            sessionTitle: r.title,
            lastMessageRole: r.last_role,
            lastMessageContent: r.last_content,
            lastMessageAt: r.last_at,
            messageCount: r.msg_count,
          });
        }
      } catch { /* tenant DB unavailable */ }
    }

    results.sort((a, b) => b.lastMessageAt - a.lastMessageAt);
    res.json({ unanswered: results });
  });

  // ── Session detail: last N messages for a specific session ──────
  app.get("/api/admin/diagnostics/session/:tenantId/:sessionId", requireSuperAdmin, (req: Request, res: Response) => {
    if (!deps.globalOps) { res.status(500).json({ error: "globalOps not available" }); return; }
    const tenantId = req.params.tenantId as string;
      const sessionId = req.params.sessionId as string;
    const limit = Math.min(Number(req.query.limit) || 20, 100);
    try {
      const ctx = deps.globalOps.open(tenantId);
      const session = ctx.db.prepare<[string], {
        id: string; kind: string; status: string; title: string | null;
        created_at: number; ended_at: number | null; compacted_summary: string | null;
        worker_role: string | null; parent_id: string | null;
      }>(`SELECT id, kind, status, title, created_at, ended_at, compacted_summary, worker_role, parent_id
          FROM sessions WHERE id = ?`).get(sessionId);
      if (!session) { res.status(404).json({ error: "session not found" }); return; }

      const messages = ctx.db.prepare<[string, number], {
        id: string; role: string; content: string; created_at: number; entry_type: string;
      }>(`SELECT id, role, content, created_at, entry_type FROM messages
          WHERE session_id = ? AND entry_type IN ('message', 'fork_tail')
          ORDER BY created_at DESC, rowid DESC LIMIT ?`).all(sessionId, limit).reverse();

      // Estimate context size (rough character count of all messages)
      const totalChars = ctx.db.prepare<[string], { total: number }>(
        `SELECT SUM(LENGTH(content)) AS total FROM messages WHERE session_id = ?`
      ).get(sessionId);

      res.json({
        session: {
          ...session,
          estimatedContextChars: totalChars?.total ?? 0,
        },
        messages: messages.map((m) => ({
          id: m.id,
          role: m.role,
          content: m.content.slice(0, 2000),
          createdAt: m.created_at,
          entryType: m.entry_type,
        })),
      });
    } catch (err) {
      res.status(500).json({ error: err instanceof Error ? err.message : String(err) });
    }
  });

  // ── Session actions: compact / retry / archive ──────────────────
  app.post("/api/admin/diagnostics/session/:tenantId/:sessionId/action",
    requireSuperAdmin,
    express.json(),
    (req: Request, res: Response) => {
      if (!deps.globalOps) { res.status(500).json({ error: "globalOps not available" }); return; }
      const tenantId = req.params.tenantId as string;
      const sessionId = req.params.sessionId as string;
      const action = (req.body as { action?: string })?.action;
      try {
        const ctx = deps.globalOps.open(tenantId);
        const session = ctx.db.prepare<[string], { id: string; status: string }>(
          `SELECT id, status FROM sessions WHERE id = ?`
        ).get(sessionId);
        if (!session) { res.status(404).json({ error: "session not found" }); return; }

        switch (action) {
          case "archive": {
            ctx.db.prepare(`UPDATE sessions SET status = 'archived', ended_at = ? WHERE id = ?`)
              .run(Date.now(), sessionId);
            res.json({ ok: true, action: "archived" });
            break;
          }
          case "delete_trailing": {
            // Delete consecutive trailing non-assistant messages (recovery cascade cleanup)
            const trailing = ctx.db.prepare<[string], { id: string; role: string }>(
              `SELECT id, role FROM messages
               WHERE session_id = ? AND entry_type IN ('message', 'fork_tail')
               ORDER BY created_at DESC, rowid DESC LIMIT 10`
            ).all(sessionId);
            let deleted = 0;
            for (const m of trailing) {
              if (m.role === "assistant") break;
              ctx.db.prepare(`DELETE FROM messages WHERE id = ?`).run(m.id);
              deleted++;
            }
            res.json({ ok: true, action: "delete_trailing", deleted });
            break;
          }
          case "retry": {
            // Enqueue a system_note to trigger a fresh turn
            enqueue(ctx, sessionId, {
              kind: "system_note",
              text: "The previous turn failed silently. Re-process the user's last message and respond.",
              meta: { internal: true },
            }).then(() => res.json({ ok: true, action: "retry" }))
              .catch((err) => res.status(500).json({ error: err instanceof Error ? err.message : String(err) }));
            return; // async
          }
          default:
            res.status(400).json({ error: `unknown action: ${action}` });
        }
      } catch (err) {
        res.status(500).json({ error: err instanceof Error ? err.message : String(err) });
      }
    },
  );

}

